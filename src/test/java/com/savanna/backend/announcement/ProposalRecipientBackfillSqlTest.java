package com.savanna.backend.announcement;

import org.junit.jupiter.api.Test;
import java.nio.file.*;
import java.sql.*;
import java.time.*;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

class ProposalRecipientBackfillSqlTest {
    private static final Path APPLY=Path.of("docs/sql/backfill-missing-proposal-recipients.sql");
    private static final Path PREVIEW=Path.of("docs/sql/preview-missing-proposal-recipients.sql");

    @Test void backfillOnlyCurrentNonSenderMembersOfUnsubmittedUnexpiredProposalsAndCanRepeatOrRollback() throws Exception {
        try (var c=DriverManager.getConnection("jdbc:h2:mem:backfill-"+UUID.randomUUID(),"sa","");var s=c.createStatement()) {
            s.execute("create table users(user_id bigint primary key)");
            s.execute("create table team(team_id bigint primary key)");
            s.execute("create table team_member(team_id bigint references team(team_id),user_id bigint references users(user_id),unique(user_id))");
            s.execute("create table announcements(announcement_id bigint primary key,title varchar,deadline date)");
            s.execute("create table expeditions(expedition_id bigint primary key,team_id bigint,announcement_id bigint references announcements(announcement_id),stage varchar,submission_completed_at timestamp)");
            s.execute("create table proposals(proposal_id bigint primary key,expedition_id bigint references expeditions(expedition_id),sender_id bigint references users(user_id))");
            s.execute("create table proposal_recipients(proposal_recipient_id bigint generated by default as identity primary key,proposal_id bigint references proposals(proposal_id),user_id bigint references users(user_id),status varchar not null,read_at timestamp,responded_at timestamp,response_version bigint not null,response_read_version bigint not null,response_read_at timestamp,unique(proposal_id,user_id))");
            s.execute("insert into users select x from system_range(1,7)");
            s.execute("insert into team values(10),(20)");
            // 1 sender; 2 joined, 3 declined, 4 pending; 5 late member; 6 other team; 7 departed.
            s.execute("insert into team_member values(10,1),(10,2),(10,3),(10,4),(10,5),(20,6)");
            LocalDate today=LocalDate.now(ZoneId.of("Asia/Seoul"));
            try(var insert=c.prepareStatement("insert into announcements values(?,?,?)")) {
                for(int i=1;i<=6;i++) {insert.setInt(1,i);insert.setString(2,"notice-"+i);insert.setObject(3,i==2?today.minusDays(1):i==4?null:i==5?today:today.plusDays(5));insert.executeUpdate();}
            }
            s.execute("insert into expeditions values(1,10,1,'KICKOFF',null),(2,10,2,'DRAFT',null),(3,10,3,'SUBMITTED',CURRENT_TIMESTAMP),(4,10,4,'KICKOFF',null),(5,10,5,'REVIEW',null),(6,10,6,'SUBMITTED',null)");
            s.execute("insert into proposals select expedition_id,expedition_id,1 from expeditions");
            s.execute("insert into proposal_recipients(proposal_id,user_id,status,read_at,responded_at,response_version,response_read_version,response_read_at) values(1,2,'JOINED',TIMESTAMP '2026-01-01 01:00:00',TIMESTAMP '2026-01-02 01:00:00',3,2,TIMESTAMP '2026-01-03 01:00:00'),(1,3,'DECLINED',null,TIMESTAMP '2026-01-02 01:00:00',2,1,null),(1,4,'PENDING',TIMESTAMP '2026-01-01 01:00:00',null,0,0,null)");
            String before=snapshot(c);
            String apply=Files.readString(APPLY),preview=Files.readString(PREVIEW);
            assertEquals(5,previewCount(c,preview)); // late member + four members for today's deadline.
            c.setAutoCommit(false);
            assertEquals(5,s.executeUpdate(apply));
            assertEquals(0,previewCount(c,preview));
            assertEquals(0,s.executeUpdate(apply));
            assertEquals(0,count(c,"select count(*) from proposal_recipients where user_id in(1,6,7)"));
            assertEquals(0,count(c,"select count(*) from proposal_recipients where proposal_id in(2,3,4,6)"));
            assertEquals(5,count(c,"select count(*) from proposal_recipients where status='PENDING' and read_at is null and responded_at is null and response_version=0 and response_read_version=0 and response_read_at is null"));
            assertEquals(before,snapshot(c));
            c.rollback();
            assertEquals(3,count(c,"select count(*) from proposal_recipients"));
            assertEquals(5,previewCount(c,preview));
            assertEquals(before,snapshot(c));
            assertEquals(5,s.executeUpdate(apply));c.commit();
            assertEquals(8,count(c,"select count(*) from proposal_recipients"));
            assertEquals(0,s.executeUpdate(apply));c.rollback();
            assertEquals(before,snapshot(c));
        }
    }
    private static int previewCount(Connection c,String sql)throws SQLException {
        try(var s=c.createStatement();var r=s.executeQuery(sql)){int n=0;while(r.next())n++;return n;}
    }
    private static long count(Connection c,String sql)throws SQLException {
        try(var s=c.createStatement();var r=s.executeQuery(sql)){r.next();return r.getLong(1);}
    }
    private static String snapshot(Connection c)throws SQLException {
        try(var s=c.createStatement();var r=s.executeQuery("select * from proposal_recipients where proposal_id=1 and user_id in(2,3,4) order by user_id")) {
            var value=new StringBuilder();while(r.next())for(int i=1;i<=r.getMetaData().getColumnCount();i++)value.append(r.getObject(i)).append('|');return value.toString();
        }
    }
}
